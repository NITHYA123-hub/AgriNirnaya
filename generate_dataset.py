def build_dataset():
    fieldnames = [
        "crop_id",
        "crop",
        "category",
        "district",
        "season",
        "soil_type",
        "min_ph",
        "max_ph",
        "nitrogen_req_kg_ha",
        "phosphorus_req_kg_ha",
        "potassium_req_kg_ha",
        "water_requirement",
        "duration_days",
        "duration_display",
        "market_apmc",
        "min_price_inr_quintal",
        "modal_price_inr_quintal",
        "max_price_inr_quintal",
        "price_trend",
        "msp_inr_quintal",
        "seed_cost_per_acre",
        "fertilizer_cost_per_acre",
        "irrigation_pest_cost_per_acre",
        "labour_harvest_cost_per_acre",
        "cultivation_cost_per_acre",
        "min_yield_quintal_per_acre",
        "expected_yield_quintal_per_acre",
        "max_yield_quintal_per_acre",
        "expected_gross_revenue_per_acre",
        "expected_net_profit_per_acre",
        "roi_percentage",
        "risk_level",
        "notes"
    ]

    rows = []
    crop_id_counter = 1

    for crop_data in CROPS_MASTER:
        total_cost = (
            crop_data["seed_cost"] +
            crop_data["fertilizer_cost"] +
            crop_data["irrigation_pest_cost"] +
            crop_data["labour_harvest_cost"]
        )
        gross_rev = crop_data["expected_yield"] * crop_data["modal_price"]
        net_profit = gross_rev - total_cost
        roi = round((net_profit / total_cost) * 100, 1) if total_cost > 0 else 0

        # 1. State-level generic row
        rows.append({
            "crop_id": f"CR_{crop_id_counter:04d}",
            "crop": crop_data["crop"],
            "category": crop_data["category"],
            "district": "All Districts",
            "season": crop_data["season"],
            "soil_type": crop_data["soil_type"],
            "min_ph": crop_data["min_ph"],
            "max_ph": crop_data["max_ph"],
            "nitrogen_req_kg_ha": crop_data["nitrogen"],
            "phosphorus_req_kg_ha": crop_data["phosphorus"],
            "potassium_req_kg_ha": crop_data["potassium"],
            "water_requirement": crop_data["water_req"],
            "duration_days": crop_data["duration_days"],
            "duration_display": crop_data["duration_display"],
            "market_apmc": "Karnataka State Average APMC",
            "min_price_inr_quintal": crop_data["min_price"],
            "modal_price_inr_quintal": crop_data["modal_price"],
            "max_price_inr_quintal": crop_data["max_price"],
            "price_trend": crop_data["price_trend"],
            "msp_inr_quintal": crop_data["msp"],
            "seed_cost_per_acre": crop_data["seed_cost"],
            "fertilizer_cost_per_acre": crop_data["fertilizer_cost"],
            "irrigation_pest_cost_per_acre": crop_data["irrigation_pest_cost"],
            "labour_harvest_cost_per_acre": crop_data["labour_harvest_cost"],
            "cultivation_cost_per_acre": total_cost,
            "min_yield_quintal_per_acre": crop_data["min_yield"],
            "expected_yield_quintal_per_acre": crop_data["expected_yield"],
            "max_yield_quintal_per_acre": crop_data["max_yield"],
            "expected_gross_revenue_per_acre": round(gross_rev, 2),
            "expected_net_profit_per_acre": round(net_profit, 2),
            "roi_percentage": roi,
            "risk_level": crop_data["risk_level"],
            "notes": crop_data["notes"]
        })
        crop_id_counter += 1

        # 2. District-specific rows
        for district in crop_data["districts"]:
            apmc = crop_data["apmc_map"].get(district, f"{district} APMC")
            # Slight regional variation in market price (+/- 2-5%) to reflect real APMC spread
            dist_hash = sum(ord(c) for c in district) % 11 - 5 # -5 to +5%
            dist_modal = round(crop_data["modal_price"] * (1 + dist_hash / 100.0))
            dist_min = round(dist_modal * 0.88)
            dist_max = round(dist_modal * 1.12)
            dist_gross = round(crop_data["expected_yield"] * dist_modal, 2)
            dist_net = round(dist_gross - total_cost, 2)
            dist_roi = round((dist_net / total_cost) * 100, 1)

            rows.append({
                "crop_id": f"CR_{crop_id_counter:04d}",
                "crop": crop_data["crop"],
                "category": crop_data["category"],
                "district": district,
                "season": crop_data["season"],
                "soil_type": crop_data["soil_type"],
                "min_ph": crop_data["min_ph"],
                "max_ph": crop_data["max_ph"],
                "nitrogen_req_kg_ha": crop_data["nitrogen"],
                "phosphorus_req_kg_ha": crop_data["phosphorus"],
                "potassium_req_kg_ha": crop_data["potassium"],
                "water_requirement": crop_data["water_req"],
                "duration_days": crop_data["duration_days"],
                "duration_display": crop_data["duration_display"],
                "market_apmc": apmc,
                "min_price_inr_quintal": dist_min,
                "modal_price_inr_quintal": dist_modal,
                "max_price_inr_quintal": dist_max,
                "price_trend": crop_data["price_trend"],
                "msp_inr_quintal": crop_data["msp"],
                "seed_cost_per_acre": crop_data["seed_cost"],
                "fertilizer_cost_per_acre": crop_data["fertilizer_cost"],
                "irrigation_pest_cost_per_acre": crop_data["irrigation_pest_cost"],
                "labour_harvest_cost_per_acre": crop_data["labour_harvest_cost"],
                "cultivation_cost_per_acre": total_cost,
                "min_yield_quintal_per_acre": crop_data["min_yield"],
                "expected_yield_quintal_per_acre": crop_data["expected_yield"],
                "max_yield_quintal_per_acre": crop_data["max_yield"],
                "expected_gross_revenue_per_acre": dist_gross,
                "expected_net_profit_per_acre": dist_net,
                "roi_percentage": dist_roi,
                "risk_level": crop_data["risk_level"],
                "notes": f"Recommended for {district}. {crop_data['notes']}"
            })
            crop_id_counter += 1

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_CSV, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Successfully generated unified dataset with {len(rows)} entries at {OUTPUT_CSV}")

if __name__ == "__main__":
    build_dataset()
